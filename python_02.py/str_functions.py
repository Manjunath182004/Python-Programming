s = "i am a coder."


print(s.endswith("er."))                      # Returns True if the string ends with the given substring   

print(s.capitalize())                         # Capitalizes the first character

print(s.replace("coder", "student"))          # Replaces all occurrences of old with new

print(s.find("a"))                            # Returns the index of the first occurrence (or -1 if not found)
print(s.find("f"))                   

print(s.count("am"))                          # Counts how many times the substring occurs



